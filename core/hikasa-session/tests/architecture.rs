/// True for the files whose types are DTOs or persisted configuration (check 6).
fn is_dto_file(rel: &str) -> bool {
    let parts: Vec<&str> = rel.split('/').collect();
    let file = parts.last().copied().unwrap_or("");
    let in_src = parts.len() >= 4 && parts[0] == "core" && parts[2] == "src";
    in_src
        && (matches!(file, "dto.rs" | "protocol.rs" | "rules.rs" | "model.rs")
            || parts[3..parts.len() - 1]
                .iter()
                .any(|d| *d == "json" || *d == "model"))
}

/// The names of the type aliases of `HashMap`/`HashSet` declared in `codes` (and aliases of those aliases).
fn hash_aliases<'a>(
    codes: impl Iterator<Item = &'a str> + Clone,
) -> std::collections::BTreeSet<String> {
    let mut aliases: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
    loop {
        let before = aliases.len();
        for code in codes.clone() {
            for at in find_token(code, "type") {
                let rest = &code[at + "type".len()..];
                let Some(end) = rest.find(';') else { continue };
                let Some((lhs, rhs)) = rest[..end].split_once('=') else {
                    continue;
                };
                let name: String = lhs.trim().chars().take_while(|c| is_ident(*c)).collect();
                let hashes = ["HashMap", "HashSet"]
                    .iter()
                    .any(|t| !find_token(rhs, t).is_empty())
                    || aliases
                        .iter()
                        .any(|a| !find_token(rhs, a.as_str()).is_empty());
                if hashes && !name.is_empty() {
                    aliases.insert(name);
                }
            }
        }
        if aliases.len() == before {
            return aliases;
        }
    }
}

/// The bodies of the items of `code` that are serialised: structs and enums that derive `Serialize` or
/// `Deserialize`, or that have a hand-written `impl … Serialize for Name` / `Deserialize<'de> for Name`.
/// Returned as `(offset, body)`.
fn serde_items(code: &str) -> Vec<(usize, &str)> {
    let mut names: Vec<String> = Vec::new();
    let mut out = Vec::new();
    let serde_trait = |text: &str| {
        !find_token(text, "Serialize").is_empty() || !find_token(text, "Deserialize").is_empty()
    };
    for at in find_token(code, "derive") {
        if !code[..at].trim_end().ends_with("#[") {
            continue;
        }
        let rest = &code[at + "derive".len()..];
        let list = balanced(rest.trim_start());
        if !serde_trait(list) {
            continue;
        }
        let after = at + "derive".len() + rest.find(list).unwrap_or(0) + list.len();
        if let Some(item) = item_body(code, after) {
            out.push(item);
        }
    }
    for at in find_token(code, "impl") {
        let header_end = code[at..].find('{').map_or(code.len(), |p| at + p);
        let header = &code[at..header_end];
        if serde_trait(header)
            && let Some(pos) = header.rfind(" for ")
        {
            let name: String = header[pos + 5..]
                .trim()
                .chars()
                .take_while(|c| is_ident(*c))
                .collect();
            if !name.is_empty() {
                names.push(name);
            }
        }
    }
    for name in names {
        for keyword in ["struct", "enum"] {
            for at in find_token(code, keyword) {
                let rest = code[at + keyword.len()..].trim_start();
                if rest.starts_with(name.as_str())
                    && !rest[name.len()..].starts_with(|c: char| is_ident(c))
                    && let Some(item) = item_body(code, at)
                {
                    out.push(item);
                }
            }
        }
    }
    out
}

/// The body of the first `struct`/`enum`/`union` item at or after `from`: its braced or parenthesised field list
/// (empty for a unit struct).
fn item_body(code: &str, from: usize) -> Option<(usize, &str)> {
    let rest = &code[from..];
    let at = ["struct", "enum", "union"]
        .iter()
        .filter_map(|kw| find_token(rest, kw).first().copied())
        .min()?;
    let item = &rest[at..];
    let open = item.find(['{', '(', ';'])?;
    if item[open..].starts_with(';') {
        return Some((from + at, ""));
    }
    let body = balanced(&item[open..]);
    Some((from + at + open, body))
}

/// `HashMap`/`HashSet` (and their aliases) in one file: anywhere in a DTO or persisted config file (§6.1 check 6),
/// and inside every serialised item of any other core source file (wave-4 review).
fn hash_violations(
    rel: &str,
    raw: &str,
    aliases: &std::collections::BTreeSet<String>,
) -> Vec<String> {
    let code = code_only(raw);
    let mut tokens: Vec<&str> = vec!["HashMap", "HashSet"];
    tokens.extend(aliases.iter().map(String::as_str));
    let mut violations = Vec::new();
    let mut flag = |at: usize, token: &str, what: &str| {
        violations.push(format!(
            "{rel}:{}: `{token}` in {what} (T5: use BTreeMap/BTreeSet)",
            line_of(&code, at)
        ));
    };
    if is_dto_file(rel) {
        for token in &tokens {
            for at in find_token(&code, token) {
                flag(at, token, "a DTO or persisted config file");
            }
        }
    } else {
        for (start, body) in serde_items(&code) {
            for token in &tokens {
                for at in find_token(body, token) {
                    flag(start + at, token, "a serialised type");
                }
            }
        }
    }
    violations.sort();
    violations.dedup();
    violations
}

fn check_no_hash_collections(root: &Path) -> Vec<String> {
    let files: Vec<(String, String)> = rust_files(&root.join("core"))
        .into_iter()
        .filter_map(|file| {
            let rel = relative(root, &file);
            let in_src = rel.split('/').nth(2) == Some("src");
            let raw = fs::read_to_string(&file).ok()?;
            in_src.then_some((rel, raw))
        })
        .collect();
    let codes: Vec<String> = files.iter().map(|(_, raw)| code_only(raw)).collect();
    let aliases = hash_aliases(codes.iter().map(String::as_str));
    let mut violations = Vec::new();
    for (rel, raw) in &files {
        violations.extend(hash_violations(rel, raw, &aliases));
    }
    violations
}

