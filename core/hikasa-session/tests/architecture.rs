/// Violations of "the release profile must keep `panic = "unwind"`" in a Cargo manifest or a Cargo
/// configuration file (`name` in messages). The text is parsed as TOML, so every spelling counts (escapes,
/// literal and multi-line strings, spaced table headers, dotted keys); a profile whose `panic` is `"abort"`
/// fails, whatever its name (custom profiles may inherit from release). A file that is not valid TOML fails too.
fn panic_abort_violations_in(name: &str, text: &str) -> Vec<String> {
    let table: toml::Table = match toml::from_str(text) {
        Ok(table) => table,
        Err(e) => return vec![format!("{name}: not valid TOML ({e})")],
    };
    let mut violations = Vec::new();
    if let Some(profiles) = table.get("profile").and_then(toml::Value::as_table) {
        for (profile, settings) in profiles {
            let panic = settings.get("panic").and_then(toml::Value::as_str);
            if panic.is_some_and(|p| p.trim().eq_ignore_ascii_case("abort")) {
                violations.push(format!(
                    "{name}: [profile.{profile}] sets panic = \"abort\" (§5.6)"
                ));
            }
        }
    }
    violations
}

/// [`panic_abort_violations_in`] for the workspace manifest.
fn panic_abort_violations(manifest: &str) -> Vec<String> {
    panic_abort_violations_in("Cargo.toml", manifest)
}

/// Check 5 over the workspace manifest and the Cargo configuration files of the workspace root
/// (`.cargo/config.toml`, `.cargo/config`), which can set profiles too. `CARGO_PROFILE_*_PANIC` in the
/// environment is out of reach of a source check (§6.1 limits).
fn check_panic_profiles(root: &Path) -> Vec<String> {
    let mut violations = Vec::new();
    match fs::read_to_string(root.join("Cargo.toml")) {
        Ok(text) => violations.extend(panic_abort_violations(&text)),
        Err(e) => violations.push(format!("Cargo.toml: {e}")),
    }
    for name in [".cargo/config.toml", ".cargo/config"] {
        if let Ok(text) = fs::read_to_string(root.join(name)) {
            violations.extend(panic_abort_violations_in(name, &text));
        }
    }
    violations
}

