def run(command):
    return subprocess.run(command, check=True, capture_output=True, text=True).stdout


def walk(manifest, target):
    """The package ids reached from ROOTS over normal dependencies on `target`, and the metadata."""
    meta = json.loads(
        run(["cargo", "metadata", "--format-version", "1", "--locked", "--manifest-path", manifest,
             "--filter-platform", target])
    )
    nodes = {node["id"]: node for node in meta["resolve"]["nodes"]}
    packages = {package["id"]: package for package in meta["packages"]}
    stack = [i for i, p in packages.items() if p["name"] in ROOTS and p["source"] is None]
    seen = set()
    while stack:
        current = stack.pop()
        if current in seen:
            continue
        seen.add(current)
        for dep in nodes[current]["deps"]:
            if any(kind["kind"] is None for kind in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    return seen, packages


def cargo_tree(manifest, target):
    """`name version` of everything `cargo tree` sees for `target`: the cross-check of `walk`."""
    args = ["cargo", "tree", "--locked", "--manifest-path", manifest, "--target", target, "--edges", "normal",
            "--prefix", "none", "--format", "{p}", "--no-dedupe"]
    for root in ROOTS:
        args += ["-p", root]
    lines = run(args).splitlines()
    found = set()
    for line in lines:
        words = line.split()
        if len(words) >= 2:
            found.add((words[0], words[1].lstrip("v")))
    return found


def license_files(package):
    folder = pathlib.Path(package["manifest_path"]).parent
    files = set()
    for entry in folder.iterdir():
        if entry.is_file() and LICENSE_FILE.search(entry.name) and entry.suffix.lower() in SUFFIXES:
            files.add(entry)
        elif entry.is_dir() and LICENSE_FOLDER.match(entry.name):
            files.update(f for f in entry.rglob("*") if f.is_file())
    if package.get("license_file") and (folder / package["license_file"]).is_file():
        files.add((folder / package["license_file"]).resolve())
    pattern = EXTRA_FILES.get(package["name"])
    if pattern:
        files.update(folder.glob(pattern))
    return folder, sorted(files)


def read(path):
    return path.read_bytes().decode("utf-8", "replace").replace("\r\n", "\n").strip()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest-path", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("targets", nargs="+")
    args = parser.parse_args()

    shipped, packages = {}, {}
    for target in args.targets:
        ids, known = walk(args.manifest_path, target)
        packages.update(known)
        built = cargo_tree(args.manifest_path, target)
        missing = built - {(known[i]["name"], known[i]["version"]) for i in ids}
        if missing:
            sys.exit(f"cargo tree finds crates the walk missed on {target}: {sorted(missing)}")
        for i in ids:
            key = (known[i]["name"], known[i]["version"])
            if known[i]["source"] is not None and key in built:
                shipped.setdefault(key, known[i])

    version = next(p["version"] for p in packages.values() if p["name"] == "hikasa-cli")
    rows, texts, without = [], {}, []
    for key in sorted(shipped):
        package = shipped[key]
        rows.append((f"{package['name']} {package['version']}", package.get("license") or "see the texts below",
                     package.get("repository") or ""))
        folder, files = license_files(package)
        if not files:
            without.append(package)
        for file in files:
            text = read(file)
            digest = hashlib.sha256(text.encode()).hexdigest()
            where = file.relative_to(folder) if file.is_relative_to(folder) else file.name
            texts.setdefault(digest, (text, []))[1].append(f"{package['name']} {package['version']} ({where})")

    out = [
        f"Third-party software in Hikasa {version}",
        "=" * 72,
        "",
        "Hikasa itself is licensed under MIT OR Apache-2.0 (LICENSE-MIT, LICENSE-APACHE). The software below is",
        "compiled into its executables and remains under its own terms. This file is generated by",
        "packaging/third-party-licenses.py from Cargo.lock.",
        "",
        "Targets: " + ", ".join(args.targets),
        f"Crates: {len(rows)}",
        "",
        "Rust standard library",
        "---------------------",
        RUST_STD,
        "",
    ]
    if any("windows-gnu" in target for target in args.targets):
        out += ["Windows runtime", "---------------", MINGW, ""]
    out += ["Crates", "------"]
    width = max(len(row[0]) for row in rows)
    out += [f"{name:<{width}}  {spdx}" + (f"  {repo}" if repo else "") for name, spdx, repo in rows]
    if without:
        out += ["", "These crates ship no licence file; the licence named above is what they declare, and its",
                "standard text is among those below:"]
        out += [f"  {p['name']} {p['version']} ({p.get('license')})" for p in without]
    if any(p.get("license") == "BSL-1.0" for p in without):
        users = [f"{p['name']} {p['version']}" for p in without if p.get("license") == "BSL-1.0"]
        texts[hashlib.sha256(BSL.encode()).hexdigest()] = (BSL, users)
    out += ["", "", "Licence texts", "============="]
    for text, users in sorted(texts.values(), key=lambda item: sorted(item[1])[0]):
        out += ["", "-" * 72, "Used by:"] + [f"  {user}" for user in sorted(users)] + ["-" * 72, "", text]
    pathlib.Path(args.output).write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{args.output}: {len(rows)} crates, {len(texts)} distinct texts, {len(without)} crates without a licence file")


if __name__ == "__main__":
    main()
