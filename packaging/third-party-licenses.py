#!/usr/bin/env python3
"""Writes THIRD_PARTY_LICENSES.txt: every crate compiled into `hikasa` and `hikasa-gui` for the given targets, with the
licence files the crates ship. Standard library only; run with `python3 -I`.

The crates come from `cargo metadata --filter-platform`, walking the normal dependencies of the two binaries (crates
used only by build scripts or tests are not shipped; proc-macros are listed, their output is in the binary). The walk
sees the features of every workspace member together, so `cargo tree` narrows it to what the two binaries really
build, and must find nothing the walk missed. Each distinct licence text appears once, after the crates that use it.

    third-party-licenses.py --manifest-path Cargo.toml --output FILE TARGET...
"""

import argparse
import hashlib
import json
import pathlib
import re
import subprocess
import sys

ROOTS = ("hikasa-cli", "hikasa-gui")
LICENSE_FILE = re.compile(r"(^|[-_.])(un)?licen[cs]e|^copying|^copyright|^notice|^mit($|[-_.])|^apache($|[-_.])", re.I)
LICENSE_FOLDER = re.compile(r"^licen[cs]es?$", re.I)
SUFFIXES = {"", ".txt", ".md", ".rst", ".mit", ".apache", ".apache2", ".bsd", ".zlib", ".unicode", ".0", ".1"}
# Fonts carry their licences beside them, outside the crate's root.
EXTRA_FILES = {"epaint_default_fonts": "fonts/*.txt"}
# Standard texts for licences a crate declares without shipping the file, when no other crate supplies them.
